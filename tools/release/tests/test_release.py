class Older(Base):
    """older-installer.py: the runner's upgrade check starts from this build at a lower version."""
    ZIP = "out/desktop-buddies-0.2.0-windows-x64.zip"

    def setUp(self):
        super().setUp()
        self.assertEqual(self.repo.pack().returncode, 0)
        self.conf = (self.repo.dir / "apps/desktop/src-tauri/tauri.conf.json").read_bytes()

    def older(self, old="0.1.5", mode=""):
        tauri = self.repo.tool("tauri", FAKE_TAURI)
        sevenzip = self.repo.tool("7z", FAKE_7Z)
        env = dict(os.environ, FAKE_MODE=mode, FAKE_RECORD=str(self.repo.dir / "record.json"))
        return subprocess.run([sys.executable, "-I", str(self.repo.dir / "apps/desktop/shell-check/older-installer.py"), "--zip", self.ZIP,
                               "--old-version", old, "--out-dir", "old", "--tauri", str(tauri), "--sevenzip", str(sevenzip)],
                              cwd=self.repo.dir, capture_output=True, text=True, env=env)

    def test_builds_the_same_files_at_a_lower_version(self):
        r = self.older()
        self.assertEqual(r.returncode, 0, r.stderr)
        setup = self.repo.dir / "old/desktop-buddies-0.1.5-setup-x64.exe"
        with zipfile.ZipFile(setup) as z:
            got = {n[len("$INSTDIR/"):]: z.read(n) for n in z.namelist() if n.startswith("$INSTDIR/")}
        top = "Desktop Buddies 0.2.0/"
        want = {n[len(top):]: d for n, d in self.repo.zip_parts().items() if n != top + "README.txt"}
        self.assertEqual(got, want)
        self.assertEqual((self.repo.dir / "apps/desktop/src-tauri/tauri.conf.json").read_bytes(), self.conf, "put back")

    def test_puts_tauri_conf_back_when_the_build_fails(self):
        r = self.older(mode="fail")
        self.assertNotEqual(r.returncode, 0)
        self.assertEqual((self.repo.dir / "apps/desktop/src-tauri/tauri.conf.json").read_bytes(), self.conf)

    def test_refuses_a_version_that_isnt_lower(self):
        for old in ("0.2.0", "0.3.0", "1.0.0", "0.2"):
            with self.subTest(old):
                r = self.older(old)
                self.refused(r, "isn't a version lower than 0.2.0")
                self.assertFalse((self.repo.dir / "old").exists())


